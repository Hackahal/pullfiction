"""Adapt modern inline M2 data to the renderer's existing MD20 input.

Generated bytes are private local cache data, never client replacements.
Unsupported effects fail explicitly. Local sequence clocks become disjoint bands,
so the existing mesh, animation and native UI code can keep its behavior.
"""
import math
import struct


class CompatError(ValueError):
    pass


class UnsupportedFeatureError(CompatError):
    """A fixed renderer capability limit, rather than absent or corrupt data."""
    pass


def read(data, fmt, offset):
    if offset < 0 or offset + struct.calcsize(fmt) > len(data):
        raise CompatError('Truncated modern model data.')
    return struct.unpack_from(fmt, data, offset)


def span(data, offset, size):
    if offset < 0 or size < 0 or offset + size > len(data):
        raise CompatError('Modern model array exceeds its file.')
    return data[offset:offset + size]


def table(data, offset, stride):
    count, start = read(data, '<II', offset)
    return [span(data, start + i * stride, stride) for i in range(count)] if count <= len(data) // stride else fail('Invalid modern model count.')


def fail(message):
    raise CompatError(message)


def unsupported(message):
    raise UnsupportedFeatureError(message)


def shader_coordinates(shader, texture_count):
    """Translate modern M2 vertex-shader inputs to explicit renderer UV selectors.

    0/1 are the two authored UV sets, 0xffff is generated reflection mapping.
    Reference: noclip.website rust/src/wow/skin.rs get_vertex_shader.
    """
    env = 0xffff
    if texture_count == 0:
        return ()
    if shader == 0x8009 and texture_count == 3:
        return (0, env, 0)
    # A packed shader with >=2 bindings always selects a two-sampler pixel shader. Some
    # authored batches retain an unused third binding (e.g. 0x4016); static shader IDs can
    # genuinely select three samples and must keep their separate capability guard.
    sampled_count = 2 if not shader & 0x8000 and texture_count >= 2 else texture_count
    if sampled_count > 2:
        raise UnsupportedFeatureError('Modern materials with more than two texture stages require the extended renderer.')
    if shader & 0x8000:
        layouts = [
            (0,env),(0,env),(0,env),(0,env,0),(0,env),(0,0),(0,0),
            (0,env),(0,env),(0,env,0),(0,0),(0,env),(0,env),(0,env),
            (0,0),(0,1),(0,env),(0,env,0),(0,),(0,),(0,env,1),
            (0,1),(0,1),(0,0),(0,env,1),(env,),(0,1,0),(0,1),
            (0,1,0),(0,0),(0,1,2),(0,1,2),(0,),(0,1),(0,),(0,1),
        ]
        index = shader & 0x7fff
        if index >= len(layouts) or len(layouts[index]) < texture_count:
            unsupported('Unknown modern material vertex shader.')
        if len(layouts[index]) > 2:
            unsupported('Modern materials with more than two texture stages require the extended renderer.')
        return layouts[index][:texture_count]
    if sampled_count == 1:
        return (env if shader & 0x80 else 1 if shader & 0x4000 else 0,)
    if shader & 0x80:
        return (env, env if shader & 8 else 0)
    return (0, env if shader & 8 else 1 if shader & 0x4000 else 0)


class Adapter:
    def __init__(self, modern, skins):
        self.parts = {}
        cursor = 0
        while cursor < len(modern):
            tag, size = read(modern, '<4sI', cursor)
            if tag in self.parts:
                fail('Duplicate modern model chunk.')
            self.parts[tag] = span(modern, cursor + 8, size)
            cursor += 8 + size
        self.b = self.parts.get(b'MD21', b'')
        magic, self.version = read(self.b, '<4sI', 0)
        if magic != b'MD20' or self.version not in (272, 274):
            fail('Expected MD21 version 272 or 274.')
        if self.version == 272 and read(self.b, '<I', 0x128)[0]:
            unsupported('Version 272 particle layout requires separate validation.')
        for tag in (b'SKID', b'AFID'):
            if any(self.parts.get(tag, b'')):
                unsupported('External modern skeleton/animation adaptation is unfinished.')
        self.sequences = table(self.b, 0x1C, 64)
        self.starts = []
        cursor = 0
        for sequence in self.sequences:
            self.starts.append(cursor)
            cursor += read(sequence, '<I', 4)[0] + 1
            if cursor > 0xFFFFFFFF:
                unsupported('Animation timeline exceeds renderer limits.')
        # Private adapter marker after the legacy header. Batch shader IDs remain verbatim;
        # the original renderer can distinguish modern pixel combiners from stock gx presets.
        self.output = bytearray(0x144) + b'PFM1\x01\x00\x00\x00'
        struct.pack_into('<4sI', self.output, 0, b'MD20', 256)
        self.skins = skins

    def append(self, data):
        self.output.extend(bytes((-len(self.output)) % 4))
        offset = len(self.output)
        self.output.extend(data)
        return offset

    def set_array(self, field, records):
        records = list(records)
        struct.pack_into('<II', self.output, field, len(records), self.append(b''.join(records)))

    def copy_array(self, old, new, stride):
        self.set_array(old, table(self.b, new, stride))

    def alias(self, slot):
        seen = set()
        while read(self.sequences[slot], '<I', 12)[0] & 0x40:
            if slot in seen:
                fail('Animation alias cycle.')
            seen.add(slot)
            slot = read(self.sequences[slot], '<H', 62)[0]
            if slot >= len(self.sequences):
                fail('Animation alias refers to an absent sequence.')
        return slot

    def track(self, offset, fmt, compressed_quaternion=False, spline=False):
        interpolation, global_id = read(self.b, '<Hh', offset)
        if interpolation > 3:
            fail('Invalid modern track interpolation.')
        if interpolation > 1 and not spline:
            unsupported('Unsupported modern track interpolation.')
        time_arrays = table(self.b, offset + 4, 8)
        value_arrays = table(self.b, offset + 12, 8)
        if len(time_arrays) != len(value_arrays):
            fail('Modern track sequence arrays disagree.')
        value_size = struct.calcsize(fmt)
        ranges, times, values = [], [], []
        slots = range(1 if global_id >= 0 else len(self.sequences))
        for slot in slots:
            source = slot if global_id >= 0 else self.alias(slot)
            first = len(times)
            if source < len(time_arrays):
                count, time_offset = read(time_arrays[source], '<II', 0)
                key_count, key_offset = read(value_arrays[source], '<II', 0)
                if count != key_count or count > len(self.b) // max(4, value_size):
                    fail('Invalid modern key arrays.')
                previous = -1
                for index in range(count):
                    time = read(self.b, '<I', time_offset + index * 4)[0]
                    if time < previous:
                        fail('Modern key timestamps are unordered.')
                    previous = time
                    times.append(time + (0 if global_id >= 0 else self.starts[slot]))
                    key = read(self.b, fmt, key_offset + index * value_size)
                    if compressed_quaternion:
                        key = tuple((v + 32768 if v < 0 else v - 32767) / 32767 for v in key)
                        values.append(struct.pack('<4f', *key))
                    else:
                        if any(isinstance(v, float) and not math.isfinite(v) for v in key):
                            fail('Invalid modern animation value.')
                        values.append(struct.pack(fmt, *key))
            if len(times) > first:
                ranges.append(struct.pack('<II', first, len(times) - 1))
            else:
                # Empty modern sequence channels hold the bind pose. A legacy track
                # needs an explicit key to keep a neighboring sequence out of this band.
                ranges.append(None)
        if any(r is None for r in ranges) and times:
            # Modern empty sequence tracks mean bind pose. The legacy range API cannot express
            # an empty band; add the channel's identity when the caller supplies one below.
            return self.track_with_defaults(offset, fmt, compressed_quaternion, spline)
        return self.pack_track(interpolation, global_id, ranges if times else [], times, values)

    def track_with_defaults(self, offset, fmt, compressed_quaternion, spline):
        # Channel identity is supplied by the enclosing block, never guessed by sampling peers.
        if offset not in self.defaults:
            fail('A modern material track needs an explicit empty-sequence default.')
        interpolation, global_id = read(self.b, '<Hh', offset)
        time_arrays, value_arrays = table(self.b, offset + 4, 8), table(self.b, offset + 12, 8)
        ranges, times, values = [], [], []
        for slot, start in enumerate(self.starts):
            source, first = self.alias(slot), len(times)
            count, to = read(time_arrays[source], '<II', 0) if source < len(time_arrays) else (0, 0)
            vn, vo = read(value_arrays[source], '<II', 0) if source < len(value_arrays) else (0, 0)
            if count != vn:
                fail('Modern animation key counts disagree.')
            if count:
                size = struct.calcsize(fmt)
                for i in range(count):
                    times.append(start + read(self.b, '<I', to + i * 4)[0])
                    value = read(self.b, fmt, vo + i * size)
                    if compressed_quaternion:
                        value = tuple((v + 32768 if v < 0 else v - 32767) / 32767 for v in value)
                    values.append(struct.pack('<4f' if compressed_quaternion else fmt, *value))
            else:
                times.append(start)
                values.append(self.defaults[offset])
            ranges.append(struct.pack('<II', first, len(times) - 1))
        return self.pack_track(interpolation, global_id, ranges, times, values)

    def pack_track(self, interpolation, global_id, ranges, times, values):
        return struct.pack('<Hh6I', interpolation, global_id, len(ranges), self.append(b''.join(ranges)),
                           len(times), self.append(b''.join(struct.pack('<I', n) for n in times)),
                           len(values), self.append(b''.join(values)))

    def channel(self, offset, fmt, default, **options):
        self.defaults[offset] = struct.pack('<4f' if options.get('compressed_quaternion') else fmt, *default)
        return self.track(offset, fmt, **options)

    def particles(self):
        count, start = read(self.b, '<II', 0x128)
        exp2 = self.parts.get(b'EXP2', b'')
        exp_count, exp_at = read(exp2, '<II', 0) if exp2 else (0, 0)
        if exp2 and exp_count != count:
            fail('Modern EXP2 count does not match particle emitters.')
        txac = self.parts.get(b'TXAC', b'')
        # TXAC stores emitter entries first, followed by material entries.
        if txac and len(txac) != (count + read(self.b, '<I', 0x70)[0]) * 2:
            fail('Modern TXAC count does not match particle emitters and materials.')
        geometry_ids = self.parts.get(b'GPID')
        if geometry_ids is not None and len(geometry_ids) != count * 4:
            fail('Modern GPID count does not match particle emitters.')
        records, variations = [], []
        for index, raw in enumerate(table(self.b, 0x128, 492)):
            base = start + index * 492
            p = bytearray(504)
            p[:24] = raw[:24]
            flags = read(raw, '<I', 4)[0]
            # Current renderer uses the original unlit bit; modern data names the lit state.
            old_flags = flags & 0xFFFF
            old_flags = old_flags & ~1 if flags & 1 else old_flags | 1
            if flags & 0x10000000:
                old_flags |= 1  # The authored multi-texture material is unlit.
            put = lambda offset, fmt, *v: struct.pack_into(fmt, p, offset, *v)
            put(4, '<I', old_flags)
            for offset in (24, 32):
                n, at = read(raw, '<II', offset)
                name = span(self.b, at, n)
                if offset == 24 and geometry_ids is not None:
                    file_id = read(geometry_ids, '<I', index * 4)[0]
                    if file_id == 0xffffffff:
                        fail('Invalid modern particle geometry file ID.')
                    if file_id:
                        name = f'__classic/{file_id}.m2\0'.encode()
                put(offset, '<II', len(name), self.append(name))
            blend, shape, color = read(raw, '<BBH', 40)
            if shape not in (1, 2, 3) or color:
                unsupported('Modern particle emitter type/color replacement requires extended support.')
            if flags & 0x10000000:
                packed = read(raw, '<H', 22)[0]
                texture_indices = [(packed >> (j * 5)) & 31 for j in range(3)]
                if any(i >= read(self.b, '<I', 0x50)[0] for i in texture_indices):
                    fail('Modern multi-texture particle index is out of range.')
                textures = table(self.b, 0x50, 16)
                if any(read(textures[i], '<I', 0)[0] != 0 for i in texture_indices):
                    unsupported('Modern particle stages require an unresolved runtime texture binding.')
                if read(p, '<I', 24)[0]:
                    unsupported('Modern multi-texture geometry particles require separate validation.')
                if txac and read(txac, '<H', index * 2)[0]:
                    unsupported('Modern animated particle texture coordinates require separate validation.')
                # The legacy record keeps its primary index; PFP5 retains all three stages.
                put(22, '<H', texture_indices[0])
            else:
                texture_indices = [read(raw, '<H', 22)[0]] * 3
            put(40, '<HH', blend, shape)
            p[44] = 2 if flags & 0x60000 == 0x60000 else 1 if flags & 0x40000 else 0
            p[46:52] = raw[46:52]
            gravity_metadata = bytes(88)
            for source, target in [(52,52),(72,80),(92,108),(112,136),(132,164),(152,192),(176,220),(200,248),(220,276),(240,304)]:
                packed_gravity = source == 132 and flags & 0x800000
                header = self.channel(base+source, '<I' if packed_gravity else '<f', (1 if source==152 else 0,))
                if source == 132 and flags & 0x800000:
                    header = bytearray(header)
                    _, _, _, _, keys, _, _, values = read(header, '<Hh6I', 0)
                    vectors = []
                    for j in range(keys):
                        x,y,z=read(self.output, '<bbh', values+j*4)
                        # Decode before interpolation. BSD-3-Clause WhiteoutFlakes
                        # M2DecodeCompressedGravity; signed magnitude selects the Z hemisphere.
                        dx, dy, magnitude = x / 128, y / 128, z * 0.042385526
                        dz = math.sqrt(max(0, (1 - dx*dx) - dy*dy))
                        vectors.append((dx*abs(magnitude), dy*abs(magnitude),
                                        math.copysign(dz*abs(magnitude), magnitude)))
                        struct.pack_into('<f', self.output, values+j*4, -z*0.04238648)
                    if any(x or y for x,y,_ in vectors):
                        tracks = []
                        for axis in range(3):
                            track = bytearray(header)
                            struct.pack_into('<I', track, 24, self.append(b''.join(
                                struct.pack('<f', v[axis]) for v in vectors)))
                            tracks.append(track)
                        gravity_metadata = struct.pack('<I', 1) + b''.join(tracks)
                p[target:target+28] = header
            def ramp(offset, fmt):
                nt,to,nv,vo = read(raw, '<4I', offset)
                if nt != nv or nt > 64: fail('Invalid modern particle lifetime ramp.')
                times=[read(self.b,'<H',to+j*2)[0] for j in range(nt)]
                return times,[read(self.b,fmt,vo+j*struct.calcsize(fmt)) for j in range(nv)]
            times,colors=ramp(260,'<3f'); alpha_times,alphas=ramp(276,'<h'); scale_times,scales=ramp(292,'<2f')
            # Modern ramps have independent timestamps and arbitrary key counts.
            # Keep authored values in the renderer extension, with safe legacy defaults.
            put(332,'<f',0.5)
            for j in range(3):
                put(336+j*4,'<I',0xFFFFFFFF)
                put(348+j*4,'<f',1.0)
            life_curves=[]
            for ts,vs,dimension,convert in [
                (times,colors,4,lambda v: [x/255 for x in v]),
                (alpha_times,alphas,2,lambda v: [v[0]/32767]),
                (scale_times,scales,3,lambda v: list(v)),
            ]:
                keys=[(t/32767,*convert(v)) for t,v in zip(ts,vs)]
                if any(keys[i][0]>keys[i+1][0] for i in range(len(keys)-1)):
                    fail('Unordered modern particle lifetime keys.')
                life_curves.append(struct.pack('<II',len(keys),self.append(b''.join(struct.pack('<'+'f'*dimension,*v) for v in keys))))
            cell_curves = []
            for offset,target in [(316,360),(332,372)]:
                ct,cv=ramp(offset,'<H')
                cell_curves.append(struct.pack('<II', len(ct), self.append(b''.join(struct.pack('<2f',t/32767,v[0]) for t,v in zip(ct,cv)))))
                if not ct: cv=[(0,),(0,)]
                if target==360:
                    put(360,'<6H',cv[0][0],cv[0][0],1,cv[0][0],cv[0][0],1)
                else: put(372,'<4H',cv[0][0],cv[0][0],cv[0][0],cv[0][0])
            p[380:408]=raw[348:376]
            p[408:412]=raw[384:388]
            p[412:436]=raw[392:416]
            p[436:468]=raw[416:448]
            points, at = read(raw,'<II',448)
            put(468,'<II',points,self.append(span(self.b,at,points*12)))
            p[476:504]=self.channel(base+456,'<B',(1,))
            cutoff, z_source, color_mul, alpha_mul = [], 0.0, 1.0, 1.0
            if exp2:
                ea = exp_at + index * 28
                z_source, color_mul, alpha_mul = read(exp2, '<3f', ea)
                nt, to, nv, vo = read(exp2, '<4I', ea + 12)
                if nt != nv or nt > 64:
                    fail('Invalid modern particle alpha-cutoff curve.')
                cutoff = [(read(exp2, '<H', to+j*2)[0]/32767,
                           read(exp2, '<h', vo+j*2)[0]/32767) for j in range(nt)]
                if any(not all(math.isfinite(v) for v in key) or not 0 <= key[0] <= 1
                       or j and cutoff[j-1][0] > key[0] for j, key in enumerate(cutoff)):
                    fail('Invalid modern particle alpha-cutoff keys.')
            if not all(math.isfinite(v) for v in (z_source, color_mul, alpha_mul)):
                fail('Invalid modern particle material multipliers.')
            # The scroll words are sign-magnitude 6.9, not signed two's complement.
            # WhiteoutFlakes m2_model_adapter.cpp, BSD-3-Clause; see third_party/whiteoutflakes.
            def scroll(value):
                return (-1 if value & 0x8000 else 1) * (value & 0x7fff) / 512
            material = struct.pack('<4I12f2If2I', flags, *texture_indices,
                raw[44]/32, raw[45]/32,
                *(scroll(v) for v in read(raw, '<4H', 476)),
                *(scroll(v) for v in read(raw, '<4H', 484)), color_mul, alpha_mul,
                len(cutoff), self.append(b''.join(struct.pack('<2f', *key) for key in cutoff)),
                z_source, read(txac, '<H', index*2)[0] if txac else 0, bool(exp2))
            variations.append(struct.pack('<2f',*read(raw,'<f',172),*read(raw,'<f',196)) + b''.join(cell_curves) + b''.join(life_curves) + struct.pack('<7f',*read(raw,'<2f',308),*read(raw,'<4f',376),float(bool(flags & 0x80000))) + material + gravity_metadata)
            records.append(p)
        self.set_array(0x13C,records)
        return variations

    def convert(self):
        self.defaults = {}
        self.output[0x10:0x14] = self.b[0x10:0x14]
        self.copy_array(0x08, 0x08, 1)
        self.copy_array(0x14, 0x14, 4)
        self.copy_array(0x24, 0x24, 2)
        lookup = table(self.b, 0x24, 2)
        self.set_array(0x2C, (struct.pack('<HH', i if read(v, '<H', 0)[0] != 0xFFFF else 0, 0) for i, v in enumerate(lookup)))
        seqs = []
        for slot, source in enumerate(self.sequences):
            seq = bytearray(68)
            seq[:4] = source[:4]
            duration = read(source, '<I', 4)[0]
            struct.pack_into('<II', seq, 4, self.starts[slot], self.starts[slot] + duration)
            seq[12:32] = source[8:28]
            struct.pack_into('<I', seq, 32, read(source, '<H', 28)[0])
            seq[36:68] = source[32:64]
            seqs.append(seq)
        self.set_array(0x1C, seqs)
        bones = []
        bone_count, bone_start = read(self.b, '<II', 0x2C)
        for i, bone in enumerate(table(self.b, 0x2C, 88)):
            base = bone_start + i * 88
            record = bytearray(bone[:12])
            record.extend(self.channel(base + 16, '<3f', (0, 0, 0)))
            record.extend(self.channel(base + 36, '<4h', (0, 0, 0, 1), compressed_quaternion=True))
            record.extend(self.channel(base + 56, '<3f', (1, 1, 1)))
            record.extend(bone[76:88])
            bones.append(record)
        self.set_array(0x34, bones)
        self.copy_array(0x3C, 0x34, 2)
        self.copy_array(0x44, 0x3C, 48)
        colors = []
        count, offset = read(self.b, '<II', 0x48)
        for i in range(count):
            base = offset + i * 40
            colors.append(self.channel(base, '<3f', (1, 1, 1)) + self.channel(base + 20, '<h', (32767,)))
        self.set_array(0x54, colors)
        textures = []
        ids = self.parts.get(b'TXID', b'')
        for i, texture in enumerate(table(self.b, 0x50, 16)):
            kind, flags = read(texture, '<II', 0)
            fdid = read(ids, '<I', i * 4)[0] if ids else 0
            n, at = read(texture, '<II', 8)
            name = f'__classic/{fdid}.blp\0'.encode() if fdid else span(self.b, at, n)
            textures.append(struct.pack('<4I', kind, flags, len(name), self.append(name)))
        self.set_array(0x5C, textures)
        count, offset = read(self.b, '<II', 0x58)
        self.set_array(0x64, (self.channel(offset + i * 20, '<h', (32767,)) for i in range(count)))
        count, offset = read(self.b, '<II', 0x60)
        self.set_array(0x74, (self.channel(offset + i * 60, '<3f', (0, 0, 0)) +
                              self.channel(offset + i * 60 + 20, '<4f', (0, 0, 0, 1)) +
                              self.channel(offset + i * 60 + 40, '<3f', (1, 1, 1)) for i in range(count)))
        for old, new in [(0x7C, 0x68), (0x84, 0x70), (0x8C, 0x78), (0x94, 0x80), (0xA4, 0x90), (0xAC, 0x98)]:
            self.copy_array(old, new, 4 if old == 0x84 else 2)
        self.output[0xB4:0xEC] = span(self.b, 0xA0, 56)
        for old, new, size in [(0xEC, 0xD8, 2), (0xF4, 0xE0, 12), (0xFC, 0xE8, 12), (0x10C, 0xF8, 2), (0x12C, 0x118, 2)]:
            self.copy_array(old, new, size)
        attachments = []
        count, offset = read(self.b, '<II', 0xF0)
        for i, a in enumerate(table(self.b, 0xF0, 40)):
            attachments.append(struct.pack('<II', read(a, '<I', 0)[0], read(a, '<H', 4)[0]) + a[8:20] + self.channel(offset+i*40+20, '<B', (1,)))
        self.set_array(0x104, attachments)
        # The shared event parser consumes timestamp-only tracks.
        events = []
        count, offset = read(self.b, '<II', 0x100)
        for i, event in enumerate(table(self.b, 0x100, 36)):
            base = offset + i * 36 + 24
            interpolation, global_id = read(self.b, '<Hh', base)
            arrays = table(self.b, base + 4, 8)
            times, ranges = [], []
            for slot, start in enumerate(self.starts):
                source, first = self.alias(slot), len(times)
                n, to = read(arrays[source], '<II', 0) if source < len(arrays) else (0, 0)
                times.extend(start + read(self.b, '<I', to + j*4)[0] for j in range(n))
                ranges.append(struct.pack('<II', first, max(first, len(times)-1)))
            events.append(event[:24] + struct.pack('<Hh4I', interpolation, global_id, len(ranges), self.append(b''.join(ranges)), len(times), self.append(b''.join(struct.pack('<I', t) for t in times))))
        self.set_array(0x114, events)
        cameras = []
        count, offset = read(self.b, '<II', 0x110)
        for i, c in enumerate(table(self.b, 0x110, 116)):
            base = offset + i * 116
            # Modern portrait FOV has a spline track. A changing FOV cannot fit legacy cameras.
            arrays = table(self.b, base + 108, 8)
            fovs = [read(self.b, '<f', read(a, '<II', 0)[1] + j*12)[0] for a in arrays for j in range(read(a, '<I', 0)[0])]
            if not fovs or any(not math.isfinite(v) or not 0 < v < math.pi for v in fovs):
                fail('Modern camera has an invalid field of view.')
            if any(abs(v - fovs[0]) > 1e-6 for v in fovs):
                unsupported('Modern camera requires nonconstant field-of-view support.')
            cameras.append(c[:4] + struct.pack('<f', fovs[0]) + c[4:12] +
                           self.channel(base+12, '<9f', (0,)*9, spline=True) + c[32:44] +
                           self.channel(base+44, '<9f', (0,)*9, spline=True) + c[64:76] +
                           self.channel(base+76, '<3f', (0,)*3, spline=True))
        lights = []
        count, offset = read(self.b, '<II', 0x108)
        for i, light in enumerate(table(self.b, 0x108, 156)):
            base = offset + i * 156
            tracks = []
            for j, (fmt, default) in enumerate([('<3f',(1,1,1)),('<f',(0,)),('<3f',(1,1,1)),('<f',(1,)),('<f',(0,)),('<f',(0,)),('<B',(1,))]):
                tracks.append(self.channel(base + 16 + j * 20, fmt, default))
            lights.append(light[:16] + b''.join(tracks))
        self.set_array(0x11C, lights)
        self.set_array(0x124, cameras)
        profiles, coordinate_lookup = [], []
        for skin in self.skins:
            if skin[:4] != b'SKIN':
                fail('Expected external SKIN file.')
            profile = bytearray()
            for field, stride in [(4, 2), (12, 2), (20, 4), (28, 48), (36, 24)]:
                records = table(skin, field, stride)
                if field == 28:
                    # `level` supplies upper range-start bits; triangle elements stay u16.
                    triangle_count = read(skin, '<I', 12)[0]
                    for record in records:
                        start = read(record, '<H', 8)[0] | (read(record, '<H', 2)[0] << 16)
                        if start + read(record, '<H', 10)[0] > triangle_count:
                            fail('Modern skin section exceeds triangle array.')
                    records = [r[:32] for r in records]
                if field == 36:
                    converted = []
                    for batch in records:
                        record = bytearray(batch)
                        shader, count = read(batch, '<H', 2)[0], read(batch, '<H', 14)[0]
                        coordinates = shader_coordinates(shader, count)
                        if count > 2 and not shader & 0x8000:
                            # Only two sampled bindings are required. The unused third record
                            # may be absent; an unresolved sampled second texture is still a gap.
                            combo = read(batch, '<H', 16)[0]
                            lookup, textures = table(self.b, 0x80, 2), table(self.b, 0x50, 16)
                            if combo + 1 >= len(lookup):
                                fail('Modern packed second-stage lookup is truncated.')
                            slot = read(lookup[combo + 1], '<H', 0)[0]
                            if slot >= len(textures):
                                fail('Modern packed second-stage texture index is out of range.')
                            ids = self.parts.get(b'TXID', b'')
                            fdid = read(ids, '<I', slot * 4)[0] if ids else 0
                            n, at = read(textures[slot], '<II', 8)
                            if not fdid and not span(self.b, at, n).rstrip(b'\0'):
                                unsupported('Modern packed material has an unresolved second-stage runtime texture.')
                        if count == 3 and shader & 0x8000:
                            combo, transforms = read(batch, '<H', 16)[0], read(batch, '<H', 22)[0]
                            lookup = table(self.b, 0x80, 2)
                            texture_records = table(self.b, 0x50, 16)
                            slots = [read(lookup[combo + stage], '<H', 0)[0] for stage in range(3)] if combo + 3 <= len(lookup) else fail('Modern third-stage texture lookup is truncated.')
                            if any(slot >= len(texture_records) for slot in slots):
                                fail('Modern third-stage texture index is out of range.')
                            kinds = [read(texture_records[slot], '<I', 0)[0] for slot in slots]
                            texture_ids = self.parts.get(b'TXID', b'')
                            def explicit_texture(slot):
                                record = texture_records[slot]
                                fdid = read(texture_ids, '<I', slot * 4)[0] if texture_ids else 0
                                n, at = read(record, '<II', 8)
                                return bool(fdid or span(self.b, at, n).rstrip(b'\0'))
                            if not explicit_texture(slots[1]):
                                unsupported('Modern third-stage material has an unresolved second-stage runtime texture.')
                            uses_base = kinds[2] == kinds[0] and kinds[2] != 0
                            if uses_base and kinds[0] not in (2, 11, 12, 13):
                                unsupported('Modern third-stage material requires an unvalidated runtime texture binding.')
                            if not uses_base and not explicit_texture(slots[2]):
                                unsupported('Modern third-stage material has an unresolved third-stage runtime texture.')
                            transform_lookup = table(self.b, 0x98, 2)
                            if any(read(transform_lookup[transforms + stage], '<H', 0)[0] != 0xffff for stage in range(3) if transforms + stage < len(transform_lookup)):
                                unsupported('Modern third-stage texture animation requires extended support.')
                        if len(coordinate_lookup) + len(coordinates) > 0xffff:
                            unsupported('Too many material coordinate combinations.')
                        struct.pack_into('<H', record, 18, len(coordinate_lookup))
                        coordinate_lookup.extend(coordinates)
                        converted.append(record)
                    records = converted
                profile.extend(struct.pack('<II', len(records), self.append(b''.join(records))))
            profile.extend(span(skin, 44, 4))
            profiles.append(profile)
        self.set_array(0x4C, profiles)
        self.set_array(0x9C, (struct.pack('<H', v) for v in coordinate_lookup))
        ribbons = []
        count, offset = read(self.b, '<II', 0x120)
        for i, ribbon in enumerate(table(self.b, 0x120, 176)):
            base = offset + i * 176
            record = bytearray(ribbon[:20])
            for field in (20, 28):
                n, at = read(ribbon, '<II', field)
                record.extend(struct.pack('<II', n, self.append(span(self.b, at, n * 2))))
            for j, (fmt, default) in enumerate([('<3f',(1,1,1)),('<h',(32767,)),('<f',(0,)),('<f',(0,))]):
                record.extend(self.channel(base + 36 + j * 20, fmt, default))
            record.extend(ribbon[116:132])
            record.extend(self.channel(base + 132, '<H', (0,)))
            record.extend(self.channel(base + 152, '<B', (1,)))
            ribbons.append(record)
        self.set_array(0x134, ribbons)
        variations = self.particles()
        if variations:
            offset = self.append(b''.join(variations))
            self.output.extend(struct.pack('<4sII', b'PFP6', offset, len(variations)))
        return bytes(self.output)


def adapt_model(modern, skins):
    return Adapter(modern, skins).convert()
